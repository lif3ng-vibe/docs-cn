#!/usr/bin/env node
/**
 * Site prebuild for the Chinese mirror — replaces the upstream
 * `bun run build:skills` step for static site builds.
 *
 * Produces the three generated artifacts Astro's publicDir serves:
 *   1. site/public/js/generated/counts.js   (command / detection counts)
 *   2. site/public/js/detect-antipatterns-browser.js  (copied from the engine)
 *   3. site/public/_data/api/*.json         (commands / patterns / skills data)
 *
 * Counts logic mirrors scripts/build.js generateCounts(); API data reuses the
 * production generator (scripts/lib/api-data.js) exactly like gen-dev-api.mjs.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readSourceFiles, readPatterns } from './lib/utils.js';
import { generateApiData } from './lib/api-data.js';
import { ANTIPATTERNS } from '../cli/engine/registry/antipatterns.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// 1. counts.js — same counting rules as upstream build.js.
const { skills } = readSourceFiles(ROOT);
const impeccableSkill = skills.find((s) => s.name === 'impeccable');
let commandCount = 0;
if (impeccableSkill) {
  const routerMatches = impeccableSkill.body.match(/^\| `[^`]+` \|/gm);
  commandCount = routerMatches ? routerMatches.length : 0;
}
const detectionCount = new Set(ANTIPATTERNS.map((rule) => rule.id)).size;

const genDir = path.join(ROOT, 'site/public/js/generated');
fs.mkdirSync(genDir, { recursive: true });
fs.writeFileSync(
  path.join(genDir, 'counts.js'),
  `// GENERATED by prebuild-site.mjs — do not edit\n` +
    `export const COMMAND_COUNT = ${commandCount};\n` +
    `export const DETECTION_COUNT = ${detectionCount};\n`,
);
console.log(`[prebuild] counts.js: ${commandCount} commands, ${detectionCount} rules`);

// 2. Browser detector for the antipattern specimen pages.
const detectorSrc = path.join(ROOT, 'cli', 'engine', 'detect-antipatterns-browser.js');
const jsDir = path.join(ROOT, 'site', 'public', 'js');
if (fs.existsSync(detectorSrc)) {
  fs.mkdirSync(jsDir, { recursive: true });
  fs.copyFileSync(detectorSrc, path.join(jsDir, 'detect-antipatterns-browser.js'));
  console.log('[prebuild] detect-antipatterns-browser.js copied');
}

// 3. Static API payloads fetched by site client JS.
const patterns = readPatterns(ROOT);
generateApiData(path.join(ROOT, 'site', 'public'), skills, patterns, ROOT);
console.log('[prebuild] _data/api/*.json written');

console.log('[prebuild] done');
